<?php

/**
 * ============================================================
 * NAIGAI_MINPAKU_BACKLINK_BEGINNER_GUIDE
 *
 * 【初心者向け：このファイルは何をするもの？】
 * ============================================================
 *
 * このファイルは、民泊系ページで表示する
 *
 *     ← 前のページに戻る
 *
 * をまとめて管理するための「共通部品」です。
 *
 *
 * ------------------------------------------------------------
 * ■ なぜ共通ファイルにしているのか
 * ------------------------------------------------------------
 *
 * 民泊には、
 *
 * ・民泊トップ
 * ・宿泊施設一覧
 * ・宿泊施設詳細
 * ・民泊ガイド
 * ・よくある質問
 * ・キャンペーン
 * ・利用規約
 * ・予約から決済までの流れ
 *
 * など多数のページがあります。
 *
 * 各ページに同じback linkコードをコピーすると、
 * 将来修正するときに全部のファイルを直す必要があります。
 *
 * そのため、
 *
 *     minpaku-internal-back-link.php
 *
 * を「正本」にして、各ページからこのファイルを呼び出します。
 *
 *
 * ------------------------------------------------------------
 * ■ このback linkを表示する場合
 * ------------------------------------------------------------
 *
 * 同じWebサイト内の別ページから移動してきた場合です。
 *
 * 例:
 *
 *     民泊ガイド
 *        ↓
 *     よくある質問
 *
 * この場合は
 *
 *     ← 前のページに戻る
 *
 * を表示します。
 *
 *
 * ------------------------------------------------------------
 * ■ 表示しない場合
 * ------------------------------------------------------------
 *
 * 次の場合は「戻るべきサイト内ページ」が確認できないため
 * back linkを表示しません。
 *
 * ・URLを直接入力してページを開いた
 * ・ブックマークから開いた
 * ・Googleなど検索サイトから開いた
 * ・別の外部サイトから開いた
 * ・ブラウザからRefererが送られてこない
 *
 *
 * ------------------------------------------------------------
 * ■ wp_get_referer() とは
 * ------------------------------------------------------------
 *
 * WordPressの関数です。
 *
 * 「現在のページへ来る直前に見ていたページURL」
 * を取得するために使用しています。
 *
 * ただし、取得できない場合もあるため、
 * Refererが無い場合はback linkを表示しません。
 *
 *
 * ------------------------------------------------------------
 * ■ なぜサイトのドメインを確認しているのか
 * ------------------------------------------------------------
 *
 * Refererが取得できても、
 *
 *     Google → このサイト
 *
 * のように外部サイトから来た可能性があります。
 *
 * そのため、
 *
 *     home_url()
 *
 * から現在サイトのホスト名を取得し、
 * Refererのホスト名と同じか確認します。
 *
 * 同じサイトの場合だけback linkを表示します。
 *
 *
 * ------------------------------------------------------------
 * ■ history.back() とは
 * ------------------------------------------------------------
 *
 * ユーザーがボタンを押したときに、
 * ブラウザ履歴の「本当に1つ前のページ」へ戻します。
 *
 * 固定URLへ戻しているのではありません。
 *
 *
 * ------------------------------------------------------------
 * ■ CSSについて
 * ------------------------------------------------------------
 *
 * この機能のための新しいCSSは作っていません。
 *
 * 民泊ですでに使用していた
 *
 *     .mnpk-back-wrap
 *     .mnpk-back-link
 *
 * をそのまま使用しています。
 *
 * そのため、back linkの色・形・余白を変更したい場合は、
 * PHPではなく既存の民泊CSSを確認します。
 *
 *
 * ------------------------------------------------------------
 * ■ 注意：checkoutは別
 * ------------------------------------------------------------
 *
 * 決済ページにある
 *
 *     ← 詳細ページに戻る
 *
 * は「前のページへ戻る」機能ではありません。
 *
 * 決済途中から宿泊施設詳細へ戻すための
 * 固定された業務導線なので、この共通処理には含めません。
 *
 * ============================================================
 */
/**
 * ============================================================
 * 民泊共通「前のページに戻る」
 * ============================================================
 *
 * 【表示する】
 * このサイト内の別ページから現在ページへ移動した場合。
 *
 * 【表示しない】
 * ・URL直接入力
 * ・ブックマーク
 * ・外部サイトからのアクセス
 * ・Refererが取得できない場合
 * ・現在ページ自身がRefererの場合
 *
 * 【デザイン】
 * 既存の
 * .mnpk-back-wrap
 * .mnpk-back-link
 * を使用するため、CSSは追加しない。
 *
 * 【対象外】
 * checkoutの「詳細ページへ戻る」のような
 * 戻り先が固定された業務導線は変更しない。
 * ============================================================
 */

if (!defined('ABSPATH')) {
    exit;
}

$referer = wp_get_referer();

if (!$referer) {
    return;
}

$home_host = wp_parse_url(
    home_url('/'),
    PHP_URL_HOST
);

$referer_host = wp_parse_url(
    $referer,
    PHP_URL_HOST
);

/*
 * 外部サイトから来た場合は表示しない。
 */
if (
    !$home_host ||
    !$referer_host ||
    strtolower($home_host) !== strtolower($referer_host)
) {
    return;
}

$request_uri = isset($_SERVER['REQUEST_URI'])
    ? wp_unslash($_SERVER['REQUEST_URI'])
    : '/';

$current_url = home_url($request_uri);

/*
 * 現在ページ自身が戻り先になる場合は表示しない。
 */
if (
    untrailingslashit($current_url)
    === untrailingslashit($referer)
) {
    return;
}
?>

<div class="mnpk-back-wrap">
    <a
        class="mnpk-back-link"
        href="<?php echo esc_url($referer); ?>"
        onclick="window.history.back(); return false;"
    >
        ← 前のページに戻る
    </a>
</div>