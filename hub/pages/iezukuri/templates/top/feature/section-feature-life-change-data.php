if (!function_exists('naigai_iez_life_change_rows_from_tsv')) {
    function naigai_iez_life_change_rows_from_tsv($text)
    {
        $rows = array();
        $lines = preg_split('/\R/u', trim((string) $text));

        foreach ($lines as $line) {
            $line = trim($line);

            if ($line === '') {
                continue;
            }

            $cols = array_map('trim', explode('|', $line));

            if (count($cols) < 6) {
                continue;
            }

            $rows[] = array(
                'item' => $cols[0],
                'before' => $cols[1],
                'action' => $cols[2],
                'after' => $cols[3],
                'photo_title' => $cols[4],
                'photo_point' => $cols[5],
            );
        }

        return $rows;
    }
}

